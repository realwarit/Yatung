import { nowrapUnits } from './nowrap';

const NB = ' ';

describe('nowrapUnits: ตัวเลขติดหน่วยในกล่องคำพูด', () => {
  it('n รายการ / n นาที / n ชม.', () => {
    expect(nowrapUnits('เลยเวลาแล้ว 2 รายการ กินเลยนะคะ')).toBe(`เลยเวลาแล้ว 2${NB}รายการ กินเลยนะคะ`);
    expect(nowrapUnits('อีก 5 นาทีค่ะ')).toBe(`อีก 5${NB}นาทีค่ะ`);
    expect(nowrapUnits('อีก 2 ชม. 5 นาทีค่ะ')).toBe(`อีก 2${NB}ชม.${NB}5${NB}นาทีค่ะ`);
  });
  it('HH:MM น.', () => expect(nowrapUnits('เวลา 18:00 น.')).toBe(`เวลา 18:00${NB}น.`));
  it('มี n ช่องที่ควรตรวจ', () => expect(nowrapUnits('มี 3 ช่องที่ควรตรวจเป็นพิเศษ')).toBe(`มี 3${NB}ช่องที่ควรตรวจเป็นพิเศษ`));
  it('ข้อความที่ไม่มีตัวเลขไม่เปลี่ยน', () => expect(nowrapUnits('วันนี้กินครบแล้ว เก่งมากเลยค่ะ')).toBe('วันนี้กินครบแล้ว เก่งมากเลยค่ะ'));
});
